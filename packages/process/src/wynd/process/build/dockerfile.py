"""Process Dockerfile rendering (PLAN §6.5; owner PROC-BUILD, M2; `$DRAFTS/04 §8.5`).

A pure function of the lock (golden-testable): venvs sorted by id, wheels by filename, `system` sorted; build inputs
bind-mounted; a final `wynd-supervisor check-plan` smoke test before switching to the non-root user. The
`dev.wynd.env-manifest` label is added by the build job (`manifest_label`), since the manifest is not in the lock.
"""

from __future__ import annotations

import json
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from wynd.spec.env_manifest import EnvManifest
    from wynd.spec.lockfiles import ProcessLock

VENV_ROOT = "/opt/wynd/venvs"
BUILD_DIR = "/opt/wynd/build"
PROCESS_DIR = "/opt/wynd/process"
SUPERVISOR = "/opt/wynd/supervisor/bin/wynd-supervisor"
PYTHON = "/usr/local/bin/python3.12"
RUN_API_PORT = "8080"


def render_dockerfile(lock: ProcessLock) -> str:
    commit = lock.commit
    lines = [
        "# syntax=docker/dockerfile:1.7",
        f"# Generated by wynd {lock.runtime_version} for process {lock.process} at commit {commit}.",
        f"# Do not edit: rebuild with `wynd build {lock.process}`.",
        f"FROM {lock.base.image}",
        "USER root",
    ]
    system = sorted(lock.system_packages)
    if system and lock.base.variant == "alpine":
        lines.append(f"RUN apk add --no-cache {' '.join(system)}")
    elif system:
        lines += [f"RUN apt-get update && apt-get install -y --no-install-recommends {' '.join(system)} \\",
                  " && rm -rf /var/lib/apt/lists/*"]
    steps_of = {venv.id: venv.steps for venv in lock.plan.venvs}
    commands: list[str] = []
    for venv in sorted(lock.venvs, key=lambda v: v.id):
        python = f"{VENV_ROOT}/{venv.id}/bin/python"
        commands.append(f"uv venv --python {PYTHON} {VENV_ROOT}/{venv.id}")
        commands.append(f"uv pip install --python {python} --no-deps --find-links /opt/wynd/wheels \\\n"
                        f"      -r {BUILD_DIR}/venvs/{venv.id}/requirements.txt")
        wheels = sorted(lock.wheels[sid].wheel.removeprefix("dist/") for sid in steps_of.get(venv.id, ()))
        if wheels:
            listed = " \\\n".join(f"      {BUILD_DIR}/dist/{wheel}" for wheel in wheels)
            commands.append(f"uv pip install --python {python} --no-deps \\\n{listed}")
    if commands:
        lines += [
            "RUN --mount=type=cache,target=/var/cache/uv,sharing=locked \\",
            f"    --mount=type=bind,source=venvs,target={BUILD_DIR}/venvs \\",
            f"    --mount=type=bind,source=dist,target={BUILD_DIR}/dist \\",
            "    " + " \\\n && ".join(commands),
        ]
    lines += [
        f"COPY process.lock.yaml process.env.yaml {PROCESS_DIR}/",
        f"RUN {SUPERVISOR} check-plan {PROCESS_DIR}/process.lock.yaml",
        "USER wynd",
        "LABEL " + " \\\n      ".join(f"{key}={_quote(value)}" for key, value in [
            ("dev.wynd.process", lock.process),
            ("dev.wynd.commit", commit),
            ("dev.wynd.base-version", lock.base.version),
            ("dev.wynd.base-variant", lock.base.variant),
            ("dev.wynd.run-api-port", RUN_API_PORT),
            ("org.opencontainers.image.revision", commit),
        ]),
    ]
    return "\n".join(lines) + "\n"


def manifest_label(manifest: EnvManifest) -> str:
    """The `dev.wynd.env-manifest` LABEL line: the manifest as compact JSON (names and descriptions, never values)."""
    compact = json.dumps(manifest.model_dump(mode="json", exclude_none=True), separators=(",", ":"),
                         sort_keys=True, ensure_ascii=False)
    return f"LABEL dev.wynd.env-manifest={_quote(compact)}\n"


def _quote(value: str) -> str:
    """A double-quoted Dockerfile value: backslash, quote and `$` escaped (LABEL values undergo env substitution)."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'
